def cron_scheduler_loop(stop_event: threading.Event):
    """Only enqueue prompts here; the agent thread performs all model/tool work."""
    while not stop_event.is_set():
        poll_due_jobs(datetime.now(CRON_TIMEZONE))
        if stop_event.wait(1.0):
            break


def start_scheduler(stop_event: threading.Event) -> threading.Thread:
    thread = threading.Thread(
        target=cron_scheduler_loop, args=(stop_event,), name="cron-scheduler", daemon=True,
    )
    thread.start()
    return thread
